def get_llm_provider(
    backend: Optional[str] = None,
    model_name: Optional[str] = None,
    config: Optional[Dict[str, Any]] = None,
    **kwargs
) -> LLMProvider:
    """
    Factory to retrieve an initialized LLMProvider instance.

    Args:
        backend: "local" (Ollama), "api" (Cloud), "gemini", or "mock". Defaults to LLM_BACKEND env var or "local".
        model_name: Optional model identifier (e.g., 'llama3:8b', 'gpt-4o-mini', 'gemini-1.5-flash').
        config: Optional configuration dictionary.
    """
    selected_backend = (backend or os.getenv("LLM_BACKEND", "local")).strip().lower()

    if selected_backend in ("mock", "offline", "test"):
        return MockLLMProvider(model_name=model_name or "mock-model", config=config)

    elif selected_backend in ("local", "onprem", "ollama"):
        host = kwargs.get("host") or os.getenv("OLLAMA_HOST", "http://localhost:11434")
        return OllamaLocalProvider(
            model_name=model_name or os.getenv("OLLAMA_MODEL", "llama3:8b"),
            host=host,
            config=config,
        )

    elif selected_backend in ("api", "cloud", "openai"):
        base_url = kwargs.get("base_url") or os.getenv("LLM_BASE_URL", "https://api.openai.com/v1")
        return APILLMProvider(
            model_name=model_name or os.getenv("API_MODEL_NAME", "gpt-4o-mini"),
            api_key=kwargs.get("api_key"),
            base_url=base_url,
            config=config,
        )

    elif selected_backend in ("gemini",):
        from .api.gemini_provider import GeminiProvider
        return GeminiProvider(
            model_name=model_name,
            api_key=kwargs.get("api_key"),
            config=config,
        )

    else:
        raise ValueError(
            f"Unknown LLM backend: '{selected_backend}'. "
            f"Supported backends are: 'local' (Ollama on-premise), 'api' (Cloud), 'gemini', or 'mock'."
        )
